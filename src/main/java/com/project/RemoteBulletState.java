package com.project;

public class RemoteBulletState {
    private final double x;
    private final double y;

    public RemoteBulletState(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }
}